print(f"{number_first} - {number_second} = {number_first - number_second}")
print(f"{number_first} * {number_second} = {number_first * number_second}")
print(f"{number_first} / {number_second} = {number_first / number_second}")

print(f"{number_first} / {number_second} = {number_first / number_second}")
print(f"{number_first} % {number_second} = {number_first % number_second}")

print(f"{number_first} ** {number_second} = {number_first ** number_second}")
